import random
import logging
from returns.result import Success, Failure
from returns.maybe import Maybe, Some, Nothing
from ..cls import StanceAnalyzer, AnalysisOutput
from .mutator import Mutator
from ..datasets import StanceDataEntry

# stance, confidence
Seed = tuple[StanceDataEntry, float]


class Fuzzer:
    """Content Fuzzer"""

    def __init__(self, analyzer: StanceAnalyzer, mutator: Mutator):

        self.analyzer = analyzer
        self.mutator = mutator
        self.population: list[Seed] = []
        self.seed_index = 0

    def _reset(self):
        self.population = []
        self.seed_index = 0

    def fuzz(self) -> tuple[list[StanceDataEntry], Seed]:
        """Returns an input generated by fuzzing a seed in the population"""
        seed = random.choice(self.population)
        seed_stance = seed[0]
        rephrased = self.mutator.mutate(seed_stance)

        # avoid empty candidate
        if len(rephrased) == 0:
            return self.fuzz()

        # mutated seed keeps the same target and stance
        return [
            {
                "text": text,
                "target": seed_stance["target"],
                "stance": seed_stance["stance"],
            }
            for text in rephrased
        ], seed

    def run(self) -> Maybe[Seed]:
        """run one iteration of fuzzing"""

        rephrased_posts, seed = self.fuzz()
        so = seed[0]["stance"]  # seed original stance
        co = seed[1]  # seed original confidence

        # execute analysis
        for p in rephrased_posts:
            match self.analyzer.analyze(p["text"], p["target"]):
                case Success((s, c)):
                    if not c:
                        continue

                    p["stance"] = s.label

                    # successful mutation if the stance is changed
                    if s.label != so:
                        return Some((p, c))

                    # otherwise, add to population if confidence is improved
                    if c and c < co:
                        self.population.append((p, c))
                case Failure(e):
                    logging.error(f"Analysis failed: {e}")
                    continue

        return Nothing

    def runs(self, original_post: StanceDataEntry, n_iters: int = 10) -> Maybe[Seed]:
        """run multiple iterations of fuzzing, return the first successful seed"""
        self.population.append((original_post, 1.0))
        for _ in range(n_iters):
            match self.run():
                case Some(seed):
                    return Some(seed)

                case Nothing:
                    continue
        return Nothing
